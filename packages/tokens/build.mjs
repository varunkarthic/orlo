// Generates dist/orlo.css from src/tokens.ts (Node >= 22.6 strips types natively).
import { mkdirSync, writeFileSync } from "node:fs";
import { primitive, semantic, space, radius, type, density, layer, motionCss } from "./src/tokens.ts";

const vars = (o, prefix) => Object.entries(o).map(([k, v]) => `  --orlo-${prefix}-${k}: ${v};`).join("\n");
const px = (o) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, v === 0 ? "0" : `${v / 16}rem`]));
const dens = (d) => Object.entries(d).map(([k, v]) => `  --orlo-${k === "control" ? "control-h" : k === "pad" ? "control-pad" : "stack-gap"}: ${v / 16}rem;`).join("\n");
const flat = (o, p) => Object.entries(o).flatMap(([k, v]) => Object.entries(v).map(([s, c]) => `  --orlo-${p}-${k}-${s}: ${c};`)).join("\n");

const css = `/* Generated by @orlo/tokens. Do not edit. */
@layer orlo.tokens {
:root {
${flat(primitive, "ramp")}
${vars(px(space), "space")}
${vars({ ...px(radius), full: "9999px" }, "radius")}
  --orlo-font-sans: ${type.family.sans};
  --orlo-font-mono: ${type.family.mono};
${vars(type.size, "text")}
${vars(type.leading, "leading")}
${vars(layer, "layer")}
${vars(motionCss, "motion")}
${dens(density.comfortable)}
  color-scheme: light dark;
}
:root, [data-orlo-theme="light"] {
${vars(semantic.light, "color")}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-orlo-theme="light"]) {
${vars(semantic.dark, "color")}
    color-scheme: dark;
  }
}
[data-orlo-theme="dark"] {
${vars(semantic.dark, "color")}
  color-scheme: dark;
}
[data-orlo-density="compact"] {
${dens(density.compact)}
}
[data-orlo-density="touch"] {
${dens(density.touch)}
}
@media (pointer: coarse) {
  :root:not([data-orlo-density]) {
${dens(density.touch)}
  }
}
@media (prefers-contrast: more) {
  :root { --orlo-color-border: var(--orlo-color-border-control); }
}
}
`;
mkdirSync(new URL("./dist/", import.meta.url), { recursive: true });
writeFileSync(new URL("./dist/orlo.css", import.meta.url), css);
console.log("tokens: wrote dist/orlo.css");
